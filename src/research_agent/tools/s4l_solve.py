"""s4l_solve 工具：基准复算编排 + 物理验证（B3 定稿 2026-08-03）。

链路：生成 GUI --run 重跑脚本 → Sim4LifeLight.exe --minimized --run（继承云端
license，headless 无 QS_SOLVER）→ h5py 直读 Output.h5 → 双 ground truth 判定：
- 基准复算：重跑结果 vs 基准 Output.h5，逐分量强场相对误差（pass ≤ 1%，实测 0.000%）；
- 方案 A 线性验证：激励幅值 ×N 重跑 vs 基准，|E| 中位比值应 ≈ N（pass ≤ 5%）。

工程纪律（pitfalls）：基准 Output.h5 重跑会被同名覆盖——先备份再复算（#29）；
GUI stdout 不可见——日志写文件（#8）；os._exit(0) 退出（#9）；Popen + 超时
taskkill /F /T 杀整棵树（#31）；license 单座——S4L 任务严格串行（#3）。

判定逻辑与编排分离：_judge 纯函数可单测。
"""

